// ─── IaC exports ──────────────────────────────────────────────────────────
ipcMain.handle('download-pulumi', async (_e, config: EnvConfig, code: string) => {
  const JSZip = require('jszip');
  const pulumiCode = generatePulumiCloudflare(config, code, true);
  const zip = new JSZip();
  zip.file('Pulumi.yaml', `name: edge-deployer-worker\ndescription: Generated by Edge Deployer\nruntime: nodejs`);
  zip.file('index.ts', pulumiCode);
  zip.file('package.json', JSON.stringify({ name: 'pulumi-cloudflare', dependencies: { '@pulumi/cloudflare': 'latest', '@pulumi/pulumi': 'latest' } }, null, 2));

  const content = await zip.generateAsync({ type: 'nodebuffer' });
  const filePath = path.join(app.getPath('downloads'), 'pulumi-cloudflare.zip');
  fs.writeFileSync(filePath, content);
  shell.openPath(path.dirname(filePath));
  return filePath;
});

ipcMain.handle('download-terraform', async (_e, config: EnvConfig, code: string) => {
  const tf = generateTerraform(config, code);
  const dir = path.join(app.getPath('downloads'), `terraform-${config.cloudProvider}`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'main.tf'), tf);
  fs.writeFileSync(path.join(dir, 'worker.js'), code);
  fs.writeFileSync(path.join(dir, 'variables.tf'), `variable "cloudflare_api_token" { type = string sensitive = true }\nvariable "cloudflare_zone_id" { type = string }\n`);
  shell.openPath(dir);
  return dir;
});

