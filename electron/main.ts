// ─── Cloudflare log tail ──────────────────────────────────────────────────
// Active tail WebSockets keyed by tailId
const activeTails = new Map<string, WebSocket>();

ipcMain.handle('cf-tail-start', async (_e, config: EnvConfig) => {
  const { cfApiToken, cfAccountId, cfScriptName } = config;
  if (!cfApiToken || !cfAccountId || !cfScriptName) {
    throw new Error('Cloudflare credentials required for log tail');
  }

  // Create a tail session via the Cloudflare API
  const res = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${cfAccountId}/workers/scripts/${cfScriptName}/tails`,
    { method: 'POST', headers: { Authorization: `Bearer ${cfApiToken}`, 'Content-Type': 'application/json' }, body: '{}' }
  );
  const json: any = await res.json();
  if (!json.success) throw new Error(`Tail failed: ${json.errors?.[0]?.message ?? 'unknown'}`);

  const { id: tailId, url: tailWsUrl } = json.result;

  // Connect WebSocket and stream logs back to renderer
  const { default: WebSocket } = await import('ws' as any).catch(() => ({ default: (global as any).WebSocket }));
  const ws = new WebSocket(tailWsUrl, ['trace-v1'], {
    headers: { Authorization: `Bearer ${cfApiToken}` },
  });

  ws.on('message', (data: any) => {
    try {
      const msg = JSON.parse(data.toString());
      if (msg.logs) {
        for (const entry of msg.logs) {
          mainWindow?.webContents.send('cf-tail-log', {
            tailId,
            message: entry.message ?? JSON.stringify(entry),
            level: entry.level ?? 'log',
            timestamp: new Date(msg.eventTimestamp ?? Date.now()).toISOString(),
          });
        }
      }
    } catch {}
  });

  ws.on('error', () => activeTails.delete(tailId));
  ws.on('close', () => activeTails.delete(tailId));

  activeTails.set(tailId, ws as any);
  return { tailId };
});

ipcMain.handle('cf-tail-stop', async (_e, tailId: string, config: EnvConfig) => {
  const ws = activeTails.get(tailId);
  if (ws) { (ws as any).close(); activeTails.delete(tailId); }

  const { cfApiToken, cfAccountId, cfScriptName } = config;
  if (cfApiToken && cfAccountId && cfScriptName) {
    await fetch(
      `https://api.cloudflare.com/client/v4/accounts/${cfAccountId}/workers/scripts/${cfScriptName}/tails/${tailId}`,
      { method: 'DELETE', headers: { Authorization: `Bearer ${cfApiToken}` } }
    ).catch(() => {});
  }
});
