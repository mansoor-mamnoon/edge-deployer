// ─── Rollback with healthcheck ─────────────────────────────────────────────
ipcMain.handle('rollback-with-healthcheck', async (_e, record: DeployRecord, config: EnvConfig) => {
  log(`Rolling back to deployment from ${new Date(record.timestamp).toLocaleString()}...`);
  try {
    const result = await rollbackDeploy(record, config, log);
    log(`✅ Rollback complete: ${result.url}`);

    if (result.url) {
      log('Running post-rollback healthcheck...');
      const health = await healthcheckDeploy(result.url, config.cloudProvider);
      if (health.ok) {
        log(`✅ Healthcheck passed (${health.latencyMs}ms)`);
      } else {
        log(`⚠️  Healthcheck failed: ${health.error ?? 'unknown error'}`);
      }
      return { ...result, health };
    }

    return result;
  } catch (err: any) {
    log(`❌ Rollback failed: ${err.message}`);
    throw err;
  }
});

