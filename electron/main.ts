let mainWindow: BrowserWindow | null = null;

function log(msg: string) {
  mainWindow?.webContents.send('deploy-log', msg);
}

// ─── Window ───────────────────────────────────────────────────────────────
function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1400,
    height: 900,
    minWidth: 1024,
    minHeight: 700,
    backgroundColor: '#121212',
    titleBarStyle: 'hiddenInset',
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
    },
  });

  mainWindow.loadURL('http://localhost:8080');
  mainWindow.on('closed', () => { mainWindow = null; });
}

app.whenReady().then(createWindow);
app.on('window-all-closed', () => { if (process.platform !== 'darwin') app.quit(); });
app.on('activate', () => { if (!mainWindow) createWindow(); });

// ─── File operations ──────────────────────────────────────────────────────
ipcMain.handle('save-file', async (_e, code: string) => {
  const { filePath, canceled } = await dialog.showSaveDialog({
    filters: [{ name: 'JavaScript', extensions: ['js'] }, { name: 'TypeScript', extensions: ['ts'] }],
  });
  if (canceled || !filePath) return false;
  fs.writeFileSync(filePath, code, 'utf-8');
  return true;
});

ipcMain.handle('open-file', async () => {
  const { filePaths, canceled } = await dialog.showOpenDialog({
    properties: ['openFile'],
    filters: [
      { name: 'JavaScript / TypeScript', extensions: ['js', 'ts', 'mjs'] },
      { name: 'All Files', extensions: ['*'] },
    ],
  });
  if (canceled || !filePaths.length) return null;
  return fs.readFileSync(filePaths[0], 'utf-8');
});

